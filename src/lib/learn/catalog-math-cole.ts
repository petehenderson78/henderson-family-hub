/**
 * Math skills, grades 3-5 (Cole's track). Grade 3 is the review/compaction
 * layer: only the fluency and "gate" standards the coherence map lists as
 * prerequisites for grade 4-5 major work, all with no prereqs (ready at once)
 * and `params.reviewOnly: true` so they can be pretested and skipped. Grade 4
 * is the full year (target: May 2027); grade 5 follows. Prereqs come earlier
 * in the array. Every skill has an `intro` for the parent (CPA order, ending
 * with a worked example).
 */

import type { Skill } from "./types";

type Spec = Omit<Skill, "subject" | "track" | "grade">;

function g3(s: Spec): Skill {
  return { subject: "math", track: "cole", grade: 3, ...s, prereqs: [], params: { reviewOnly: true, ...(s.params ?? {}) } };
}

function g4(s: Spec): Skill {
  return { subject: "math", track: "cole", grade: 4, ...s };
}

function g5(s: Spec): Skill {
  return { subject: "math", track: "cole", grade: 5, ...s };
}

